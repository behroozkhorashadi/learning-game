"""Generates frontend/src/types/generated.ts from the backend's Pydantic/SQLModel
models — PRD §9: "generate the frontend TypeScript types from the Pydantic/
SQLModel models so the two sides cannot drift."

Hand-rolled JSON-schema -> TS converter (via `model_json_schema()`), so this is
a single Python invocation with no Node-side dependency. Re-run with
`make gen-types` after changing any model in app/models/. Do not hand-edit the
output file.
"""

